def require(condition, message):
    if not condition:
        raise ValueError(message)


def digest(raw):
    return hashlib.sha256(raw).hexdigest()


def encoded(value):
    return (json.dumps(value, indent=2, ensure_ascii=False, allow_nan=False) + "\n").encode()


def eligible(index, traits, field, pool, match, exotic):
    # A current zero-weight roll is legal; reusable/direct/enhanced references alone are not.
    return (not exotic and index in traits and field == "randomizedPlugSetHash"
            and pool.get("isFakePlugSet") is False and match.get("plugItemHash") == BASE
            and match.get("currentlyCanRoll") is True)


def validate_membership(rows):
    fields = ("id", "hash", "socket", "perkHash", "plugSetHash")
    require(type(rows) is list and all(type(r) is dict and set(r) == set(fields)
            and type(r["id"]) is str and all(type(r[k]) is int for k in fields[1:])
            for r in rows), "Exact roll schema")
    keys = [tuple(r[k] for k in fields) for r in rows]
    require(len(keys) == len(set(keys)) == 3 and set(keys) == EXPECTED, "Exact selected3 sockets")


def validate_resource(resource):
    require(set(resource) == {"stage", "perk", "weapons"} and resource["stage"] == "W177"
            and encoded(resource["perk"]) == encoded(PERK), "Exact resource schema/mechanics")
    validate_membership(resource["weapons"])


def generate(args):
    root = args.root.resolve()
    paths = {k: root / k for k in PINS if "/" in k}
    paths.update(inventory=args.inventory, plugSets=args.shared_sources_dir / "bungie-plugsets.json",
                 manifest=args.shared_sources_dir / "manifest.json", clarity=args.clarity)
    data, sources = {}, {}
    for key, path in paths.items():
        raw = path.read_bytes()
        require(digest(raw) == PINS[key], "Source SHA256 mismatch: " + key)
        data[key] = json.loads(raw)
        # Stable source identifiers keep generated bytes independent of temporary cache locations.
        sources[key] = {"sha256": digest(raw), "bytes": len(raw)}
    catalog = data["src/main/resources/destiny/weapons/w30.json"][:]
    selected = data["src/main/resources/destiny/weapons/w40-characteristics.json"][:]
    for file in ("w83-exotics.json", "w84-exotics.json"):
        for row in data["src/main/resources/destiny/weapons/" + file]:
            catalog.append(row["catalog"])
            selected.append(row["characteristics"])
    require(len(catalog) == len(selected) == len({w["id"] for w in selected})
            == len({w["bungieHash"] for w in selected}) == 65
            and {w["id"] for w in selected} == {w["id"] for w in catalog}, "Exact selected65")
    inv, pools, response = (data[k] for k in ("inventory", "plugSets", "manifest"))
    ipath = "/common/destiny2_content/json/en/DestinyInventoryItemDefinition-" + SUFFIX
    ppath = ipath.replace("DestinyInventoryItemDefinition-", "DestinyPlugSetDefinition-")
    require(response["ErrorCode"] == 1 and response["Response"]["version"] == VERSION
            and response["Response"]["jsonWorldComponentContentPaths"]["en"]["DestinyInventoryItemDefinition"] == ipath
            and response["Response"]["jsonWorldComponentContentPaths"]["en"]["DestinyPlugSetDefinition"] == ppath,
            "Same pinned official manifest")
    provenance = data["art/weapons/w40/provenance.json"]
    require(provenance["manifest"] == {"version": VERSION, "path": ipath}
            and provenance["cachedInventorySha256"] == PINS["inventory"], "Selected inventory provenance")
    same_name = {item["hash"] for item in inv.values()
                 if item.get("displayProperties", {}).get("name") == "Heating Up"}
    require(same_name == {BASE, ENHANCED}, "Unknown same-name Heating Up definition")
    definitions = []
    for h in sorted(same_name):
        item = inv[str(h)]
        require(item["hash"] == h and item["itemType"] == 19 and not item["redacted"]
                and not item["blacklisted"] and not item["plug"]["isDummyPlug"]
                and item["itemTypeDisplayName"] == ("Trait" if h == BASE else "Enhanced Trait"),
                "Exact base/enhanced definition")
        definitions.append({"hash": h, "description": item["displayProperties"]["description"],
                            "accepted": h == BASE, "reason": "BASE" if h == BASE else "ENHANCED_EXCLUDED"})
    rows, scans, proofs, excluded, direct = [], [], [], [], []
    for w in selected:
        item = inv[str(w["bungieHash"])]
        require(item["hash"] == w["bungieHash"] and item["itemType"] == 3 and not item["redacted"]
                and not item["blacklisted"] and (item["inventory"]["tierType"] == 6) == w["exotic"],
                "Official selected identity")
        if not w["exotic"]:
            require({k: v["value"] for k, v in item["stats"]["stats"].items()} == w["stats"], "Selected stats")
        sockets = item.get("sockets", {})
        traits = {n for c in sockets.get("socketCategories", []) if c["socketCategoryHash"] == TRAIT
                  for n in c["socketIndexes"]}
        scan = {"id": w["id"], "hash": item["hash"], "exotic": w["exotic"],
                "traitSocketIndexes": sorted(traits), "scannedSocketCount": len(sockets.get("socketEntries", [])),
                "referencedPools": []}
        for index, socket in enumerate(sockets.get("socketEntries", [])):
            hashes = {socket["singleInitialItemHash"], *[p["plugItemHash"] for p in socket.get("reusablePlugItems", [])]}
            direct.extend({"id": w["id"], "socket": index, "perkHash": h} for h in sorted(hashes & same_name))
            for field in ("randomizedPlugSetHash", "reusablePlugSetHash"):
                ph = socket.get(field)
                if not ph:
                    continue
                pool = pools[str(ph)]
                require(pool["hash"] == ph and not pool["redacted"] and not pool["blacklisted"], "Referenced pool")
                matches = [{"index": n, "item": p} for n, p in enumerate(pool.get("reusablePlugItems", []))
                           if p["plugItemHash"] in same_name]
                scan["referencedPools"].append({"socket": index, "field": field, "plugSetHash": ph,
                                               "isFakePlugSet": pool["isFakePlugSet"], "matchingEntries": matches})
                for match in matches:
                    if not eligible(index, traits, field, pool, match["item"], w["exotic"]):
                        excluded.append({"id": w["id"], "socket": index, "field": field,
                                         "plugSetHash": ph, "isFakePlugSet": pool["isFakePlugSet"], "match": match})
                        continue
                    require(item["inventory"]["tierType"] == 5, "Legendary owner")
                    row = {"id": w["id"], "hash": item["hash"], "socket": index, "perkHash": BASE, "plugSetHash": ph}
                    rows.append(row)
                    proofs.append({**row, "socketCategoryHash": TRAIT, "socketEntry": socket,
                                   "plugSetField": field, "isFakePlugSet": False, "matchingEntries": [match]})
        scans.append(scan)
    validate_membership(rows)
    base = data["clarity"][str(BASE)]
    lines = ["".join(line.get("text", "") for line in block.get("linesContent", []))
             for block in base["descriptions"]["en"] if "linesContent" in block]
    require(base["hash"] == BASE and base["name"] == "Heating Up" and base["type"] == "Weapon Trait"
            and lines == ["Weapon Kills grant a Stack of Heating Up for 5.5 seconds. Maximum of 2 Stacks.",
                "Benefits at 1|2 Stacks of Heating Up:", "• 15|30 Stability", "• 20|40 Recoil Direction",
                "• 15%|25% decreased Accuracy Cone Size", "• 15%|25% decreased Accuracy Cone Growth",
                "Buff remains active while stowed."], "Exact base Clarity mechanics")
    resource = {"stage": "W177", "perk": PERK, "weapons": rows}
    validate_resource(resource)
    outputs = {TARGET: resource,
        ART + "official-sockets.json": {"stage": "W177", "manifestVersion": VERSION,
            "inventoryUrl": "https://www.bungie.net" + ipath, "plugSetsUrl": "https://www.bungie.net" + ppath,
            "selectedCount": 65, "definitions": definitions, "accepted": proofs, "scans": scans,
            "excluded": excluded, "directReferencesNotAuthorizing": direct},
        ART + "clarity-source.json": {"stage": "W177", "repository": "https://github.com/Database-Clarity/Live-Clarity-Database",
            "commit": CLARITY_COMMIT, "url": "https://raw.githubusercontent.com/Database-Clarity/Live-Clarity-Database/"
                + CLARITY_COMMIT + "/descriptions/clarity.json", "sourceSha256": PINS["clarity"],
            "base": base, "enhancedExcludedHash": ENHANCED, "verifiedMechanics": PERK,
            "localPolicy": "20 ticks/s; valid paid weapon kills refresh110 at cap2; exact deadline expired; pure clock guards. "
                "Master owns reload survival, source identity and hidden damage attribution; source guarantees stow only."}}
    outputs[ART + "manifest.json"] = {"stage": "W177", "feature": "heating_up", "sources": sources,
        "generator": {"path": SCRIPT, "sha256": digest((root / SCRIPT).read_bytes())},
        "scannerReference": "scripts/build_stats_for_all_profile_w176.py",
        "selectedCount": 65, "supported": rows, "excludedEnhancedHash": ENHANCED,
        "outputs": {k: {"sha256": digest(encoded(v)), "bytes": len(encoded(v))} for k, v in outputs.items()},
        "nativeQa": "PENDING_MASTER_INTEGRATION"}
    return outputs, paths


def self_test(outputs):
    original, rejected = outputs[TARGET], []
    mutations = [lambda r: r.update(stage="W176"), lambda r: r.update(extra=True),
        lambda r: r["perk"].update(hash=ENHANCED), lambda r: r["perk"].update(durationTicks=130),
        lambda r: r["perk"].update(maxStacks=3), lambda r: r["perk"].update(remainsWhileStowed=False),
        lambda r: r["perk"].update(stabilityBonus=[0, 20, 30]),
        lambda r: r["perk"].update(recoilDirectionBonus=[0, 15, 30]),
        lambda r: r["perk"].update(accuracyScalar=[1.0, .85, .85]),
        lambda r: r["perk"].update(damageBonus=10), lambda r: r["weapons"].pop(),
        lambda r: r["weapons"].append(r["weapons"][0]), lambda r: r["weapons"][0].update(socket=4),
        lambda r: r["weapons"][0].update(plugSetHash=1), lambda r: r["weapons"][0].update(perkHash=ENHANCED),
        lambda r: r["weapons"][0].update(hash=1), lambda r: r["weapons"][0].update(id="ace_of_spades"),
        lambda r: r["weapons"][0].update(extra=True), lambda r: r["weapons"][0].update(socket=3.5)]
    for n, edit in enumerate(mutations):
        bad = copy.deepcopy(original)
        edit(bad)
        try:
            validate_resource(bad)
        except (ValueError, KeyError, TypeError):
            rejected.append("resource mutation " + str(n))
        else:
            raise ValueError("Accepted resource mutation " + str(n))
    pool = {"isFakePlugSet": False}
    match = {"plugItemHash": BASE, "currentlyCanRoll": True, "weight": 0}
    require(eligible(3, {3}, "randomizedPlugSetHash", pool, match, False), "Current zero-weight is eligible")
    for name, index, traits, field, p, m, exotic in (
        ("fake", 3, {3}, "randomizedPlugSetHash", {"isFakePlugSet": True}, match, False),
        ("reusable", 3, {3}, "reusablePlugSetHash", pool, match, False),
        ("nontrait", 3, {4}, "randomizedPlugSetHash", pool, match, False),
        ("exotic", 3, {3}, "randomizedPlugSetHash", pool, match, True),
        ("enhanced", 3, {3}, "randomizedPlugSetHash", pool, {**match, "plugItemHash": ENHANCED}, False),
        ("unrollable", 3, {3}, "randomizedPlugSetHash", pool, {**match, "currentlyCanRoll": False}, False),
        ("missing rollability", 3, {3}, "randomizedPlugSetHash", pool, {"plugItemHash": BASE}, False)):
        require(not eligible(index, traits, field, p, m, exotic), "Accepted " + name)
        rejected.append(name)
    return rejected


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--verify", action="store_true")
    parser.add_argument("--self-test", action="store_true")
    parser.add_argument("--root", type=Path, default=ROOT)
    parser.add_argument("--output-root", type=Path)
    parser.add_argument("--inventory", type=Path, default=Path("/tmp/destiny-weapons-w30/bungie-items.json"))
    parser.add_argument("--shared-sources-dir", type=Path, default=Path("/tmp/destiny-weapons-w60"))
    parser.add_argument("--clarity", type=Path, default=Path("/private/tmp/w167-clarity.json"))
    args = parser.parse_args()
    try:
        require(not (args.verify and args.output_root), "--verify cannot write --output-root")
        outputs, paths = generate(args)
        rejected = self_test(outputs) if args.self_test else []
        if args.self_test:
            repeat, _ = generate(args)
            require({k: encoded(v) for k, v in outputs.items()} == {k: encoded(v) for k, v in repeat.items()},
                    "Nondeterministic extraction")
        destination = (args.output_root or args.root).resolve()
        inputs = {p.resolve() for p in paths.values()} | {(args.root / SCRIPT).resolve()}
        for relative, value in outputs.items():
            target = (destination / relative).resolve()
            require(target.is_relative_to(destination) and target not in inputs, "Output aliases source/escapes root")
            if args.verify:
                require(target.read_bytes() == encoded(value), "Generated bytes differ: " + relative)
            else:
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_bytes(encoded(value))
        print(json.dumps({"stage": "W177", "status": "VERIFY_PASS" if args.verify else "GENERATED",
            "selectedScanned": 65, "supported": 3, "deterministicRepeat": args.self_test,
            "negativeCasesRejected": rejected, "outputs": list(outputs)}, indent=2))
    except (OSError, ValueError, KeyError, TypeError) as error:
        print("W177 extraction failed: " + str(error), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
