def expected_output_paths():
    """Exact persistent generator scope; independent of worktree bootstrap files."""
    paths = {ASSETS / f'items/{KEY}.json'}
    for part in ('body', 'magazine', 'cover'):
        paths.add(ASSETS / f'models/{KEY}_{part}.json')
        for frame in range(21):
            for grip in ('native', 'twohand'):
                paths.add(ASSETS / f'models/{KEY}_{frame:02}_{part}_{grip}.json')
    paths.update(ART / name for name in (
        'original-model-audit.json', 'partition-audit.json', 'partition-contact.png',
        'preview-contact.png', 'inspection.bbmodel', 'manifest.json'))
    assert len(paths) == 136
    return paths


def write_outputs(output, check=False):
    # Validate the complete inventory before the first mkdir/write or byte check.
    # Batch/export ownership remains an external integration concern.
    allowed = expected_output_paths()
    unexpected = set(output) - allowed
    assert not unexpected, 'Not an exact generated path: ' + ', '.join(sorted(map(str, unexpected)))
    missing = allowed - set(output)
    assert not missing, 'Missing generated paths: ' + ', '.join(sorted(map(str, missing)))
    for path, data in output.items():
        rel = str(path.relative_to(ROOT))
        if check:
            assert path.is_file() and path.read_bytes() == data, 'Generated drift: ' + rel
        else:
            path.parent.mkdir(parents=True, exist_ok=True); path.write_bytes(data)


