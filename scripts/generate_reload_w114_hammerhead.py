def preview(original, audit):
    """Offline orthographic assembly preview; deliberately not a native QA image."""
    from PIL import Image, ImageDraw
    image = Image.new('RGB', (1680, 1080), '#151c28'); draw = ImageDraw.Draw(image)
    colors = dict(body=(135, 150, 169), magazine=(240, 182, 61), cover=(53, 190, 185))
    for tile, frame in enumerate((0, 3, 6, 9, 12, 15, 18, 20)):
        x0, y0 = tile % 4 * 420, tile // 4 * 510 + 30
        polygons = []
        for part in PARTS:
            transform = pose_for(part, frame, original['display'])[FP[0]]
            for index in audit['indices'][part]:
                e = original['elements'][index]
                corners = []
                for mask in range(8):
                    point = [e['to' if mask >> a & 1 else 'from'][a] - 8 for a in range(3)]
                    point = rotate([point[i] * transform['scale'][i] for i in range(3)], transform['rotation'])
                    corners.append([point[i] + transform['translation'][i] for i in range(3)])
                for face in ((0, 1, 3, 2), (0, 4, 5, 1), (0, 2, 6, 4), (7, 6, 2, 3), (7, 3, 1, 5), (7, 5, 4, 6)):
                    ps = [corners[i] for i in face]
                    screen = [(x0 + 245 + (p[2] * .86 + p[0] * .5) * 12,
                               y0 + 290 - (p[1] + p[0] * .18 - p[2] * .15) * 12) for p in ps]
                    polygons.append((sum(p[0] - p[2] * .5 for p in ps), screen, colors[part]))
        for _, polygon, color in sorted(polygons, key=lambda p: p[0]):
            draw.polygon(polygon, fill=color, outline=(40, 48, 58))
        draw.text((x0 + 12, y0), f'Hammerhead {frame:02}/20  p={frame / 20:.2f}', fill='white')
    draw.text((15, 1045), 'OFFLINE ORTHOGRAPHIC PART PREVIEW | body grey / feed gold / Cover cyan | no hands, textures unchanged in product; native visibility pending', fill='white')
    return png_bytes(image)


