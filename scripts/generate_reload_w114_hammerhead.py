def surface_distance(points, triangles):
    """Actual point/triangle Euclidean distance: plane interior or nearest edge.

    numpy only batches arithmetic. Degenerate triangles reduce to their edges.
    This audits centre + six face-centres independently of clipping/bounds.
    """
    import numpy as np
    t = np.asarray(triangles, dtype=float)
    a, b, c = t[:, 0], t[:, 1], t[:, 2]
    ab, ac = b - a, c - a
    normal = np.cross(ab, ac)
    n2 = np.einsum('ij,ij->i', normal, normal)
    results = []
    for point in points:
        p = np.asarray(point)
        distance = np.full(len(t), np.inf)
        for u, v in ((a, b), (b, c), (c, a)):
            edge = v - u
            e2 = np.einsum('ij,ij->i', edge, edge)
            f = np.clip(np.einsum('ij,ij->i', p - u, edge) / np.maximum(e2, 1e-30), 0, 1)
            delta = p - u - f[:, None] * edge
            distance = np.minimum(distance, np.einsum('ij,ij->i', delta, delta))
        h = np.einsum('ij,ij->i', p - a, normal)
        projected = p - (h / np.maximum(n2, 1e-30))[:, None] * normal
        inside = n2 > 1e-20
        for u, v in ((a, b), (b, c), (c, a)):
            inside &= np.einsum('ij,ij->i', np.cross(v - u, projected - u), normal) >= -1e-10
        distance = np.where(inside, np.minimum(distance, h * h / np.maximum(n2, 1e-30)), distance)
        results.append(round(float(np.sqrt(distance.min())), 9))
    return results


def partition(triangles, original):
    helper = runpy.run_path(str(ROOT / 'scripts/generate_reload_models_w100.py'))
    clip, area = helper['clip_polygon'], helper['polygon_area']
    bypart = {p: [t['points'] for t in triangles if t['part'] == p] for p in PARTS}
    rows = []
    for i, cube in enumerate(original['elements']):
        votes = collections.defaultdict(float)
        semantics = collections.defaultdict(float)
        for t in triangles:
            low, high = t['bounds']
            if any(high[a] < cube['from'][a] or low[a] > cube['to'][a] for a in range(3)):
                continue
            polygon = t['points']
            for axis in range(3):
                polygon = clip(polygon, axis, cube['from'][axis], 1)
                polygon = clip(polygon, axis, cube['to'][axis], -1)
                if not polygon:
                    break
            value = area(polygon)
            if value > 1e-10:
                votes[t['part']] += value
                semantics[t['mesh'], t['component'], t['material'], t['bone']] += value
        center = [(a + b) / 2 for a, b in zip(cube['from'], cube['to'])]
        samples = [center] + [[cube[side][axis] if a == axis else center[a] for a in range(3)]
                              for axis in range(3) for side in ('from', 'to')]
        distances = {p: surface_distance(samples, bypart[p]) for p in PARTS}
        means = {p: sum(v) / len(v) for p, v in distances.items()}
        selected = max(PARTS, key=lambda p: votes[p]) if sum(votes.values()) > 1e-8 else min(PARTS, key=means.get)
        rows.append(dict(index=i, part=selected, elementSha256=sha(encode(cube)),
            clippedArea={p: round(votes[p], 9) for p in PARTS},
            selection='maximum actual clipped source triangle area' if sum(votes.values()) > 1e-8 else 'minimum mean seven-point source surface distance',
            samplePoints=samples, sampleSurfaceDistances=distances,
            sampleMeanDistance={p: round(v, 9) for p, v in means.items()},
            sampleWinner=min(PARTS, key=means.get),
            sourceComponents=[dict(mesh=k[0], component=k[1], material=k[2], bone=k[3], clippedArea=round(v, 9))
                              for k, v in sorted(semantics.items())]))
    indices = {p: [r['index'] for r in rows if r['part'] == p] for p in PARTS}
    assert sorted(sum(indices.values(), [])) == list(range(223))
    assert all(indices[p] for p in PARTS)
    metrics = {}
    for p in PARTS:
        total = sum(r['clippedArea'][p] for r in rows)
        carried = sum(r['clippedArea'][p] for r in rows if r['part'] == p)
        metrics[p] = dict(cubes=len(indices[p]), capturedClippedSemanticAreaFraction=round(carried / total, 9),
                          carriedOtherSourceArea=round(sum(sum(v for k, v in r['clippedArea'].items() if k != p) for r in rows if r['part'] == p), 9))
    return dict(sourceCubes=223, compositeCubes=223, maxCompositeCubes=256, indices=indices,
        classification='rigid skin + connected components + material semantics, clipped triangle area, seven-point Euclidean triangle distance audit',
        boundsUsedOnlyForBroadPhase=True, sampleOrder='centre, -X,+X,-Y,+Y,-Z,+Z face centres',
        distanceUnits='original generated model units', metrics=metrics,
        mixedCubeIndices=[r['index'] for r in rows if sum(v > 1e-8 for v in r['clippedArea'].values()) > 1],
        surfaceDisagreementIndices=[r['index'] for r in rows if r['sampleWinner'] != r['part']],
        noIntersectionIndices=[r['index'] for r in rows if not any(r['clippedArea'].values())],
        conservation='all original whole elements, faces, UV, texture references exactly once, no closure faces or rebake',
        limitation='W30 cuboids merge source boundaries; maximum clipped area owns a whole cube. Mixed seams and sample disagreements are reported, not claimed exact.', cubes=rows)


def rotate(vector, rotation):
    x, y, z = vector
    a, b, c = map(math.radians, rotation)
    x, y = x * math.cos(c) - y * math.sin(c), x * math.sin(c) + y * math.cos(c)
    x, z = x * math.cos(b) + z * math.sin(b), -x * math.sin(b) + z * math.cos(b)
    y, z = y * math.cos(a) - z * math.sin(a), y * math.sin(a) + z * math.cos(a)
    return [x, y, z]


def sample(progress):
    if not math.isfinite(progress) or not 0 <= progress <= 1:
        raise ValueError(progress)
    for a, b in zip(KEYS, KEYS[1:]):
        if progress <= b[0]:
            u = (progress - a[0]) / (b[0] - a[0]); u = u * u * (3 - 2 * u)
            return (*[[a[c][i] + (b[c][i] - a[c][i]) * u for i in range(3)] for c in (1, 2, 3)],
                    a[4] + (b[4] - a[4]) * u)
    raise ValueError('Gameplay-reviewed keys required')


def pose_for(part, frame, base):
    display = copy.deepcopy(base)
    if frame in (0, 20):
        return display
    rotation, translation, feed, angle = sample(frame / 20)
    # Source Cover TransformLink: world (0,22.1016,26.9217) centimetres.
    # Undo the -90X/100 carrier -> source (0,-.269217,.221016), then W30 map.
    # Relative to model centre, this is the actual original hinge position.
    pivot = [0, .22101600646972656 * 23.3089771408205, -.2692169761657715 * 23.3089771408205]
    for context in FP:
        transform = display[context]
        body_rotation = [v + rotation[i] for i, v in enumerate(transform['rotation'])]
        local_offset = feed if part == 'magazine' else [0, 0, 0]
        # Cover rotates around original hinge, not model origin. Rigid translation
        # p-Rp keeps the hinge stationary under the shared body transform.
        if part == 'cover':
            turned = rotate(pivot, [angle, 0, 0])
            local_offset = [pivot[i] - turned[i] for i in range(3)]
            # Compose Rbody * Rx(cover); convert with quaternion rotationXYZ semantics.
            matrix = [[rotate(rotate([int(k == j) for k in range(3)], [angle, 0, 0]), body_rotation)[i]
                       for j in range(3)] for i in range(3)]
            transform['rotation'] = [round(math.degrees(v), 6) for v in
                (math.atan2(-matrix[1][2], matrix[2][2]), math.asin(max(-1, min(1, matrix[0][2]))), math.atan2(-matrix[0][1], matrix[0][0]))]
        else:
            transform['rotation'] = [round(v, 6) for v in body_rotation]
        delta = rotate([local_offset[i] * transform['scale'][i] for i in range(3)], body_rotation)
        transform['translation'] = [round(v + translation[i] + delta[i], 6) for i, v in enumerate(transform['translation'])]
    return display


