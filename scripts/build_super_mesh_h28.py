#!/usr/bin/env python3
"""Deterministic compiled mesh props, from committed colored derivative intermediates.
No Blender/Blockbench connection, original binaries, textures, or artist-file writes.
Use --verify to compare generated bytes without writing runtime assets.
"""
import argparse
import copy
import hashlib
import json
import os
from pathlib import Path
import subprocess
import tempfile
import struct
import zlib

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / "src/main/resources/assets/destiny"
SOURCE = ROOT / "art/mesh/supers/h28"


def encode(value):
    return (json.dumps(value, ensure_ascii=False, separators=(",", ":")) + "\n").encode()


def generate():
    java_home = Path(os.environ["JAVA_HOME"])
    cache = Path.home() / ".gradle/caches/modules-2/files-2.1"
    deps = ("io.github.toxicity188/java-mesh/0.0.1", "com.google.code.gson/gson/2.14.0",
            "org.joml/joml/1.10.9", "it.unimi.dsi/fastutil/8.5.18")
    jars = [next((cache / dep).glob("*/*.jar")) for dep in deps]
    classpath = os.pathsep.join(map(str, jars))
    output = {}
    def chunk(kind, data):
        return struct.pack(">I", len(data)) + kind + data + struct.pack(">I", zlib.crc32(kind + data))
    size = 128
    pixels = b"".join(b"\0" + b"".join(b"\xff\xff\xff" + bytes([255 if x <= y else 0])
                                          for x in range(size)) for y in range(size))
    output[ASSETS / "textures/item/supers/mesh_triangle_h28.png"] = (
        b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", size, size, 8, 6, 0, 0, 0))
        + chunk(b"IDAT", zlib.compress(pixels)) + chunk(b"IEND", b""))
    manifest = {"source": "Converted source mesh derivatives; not open-licensed assets. See design42.",
                "models": {}, "compiler_dependencies": {
                    dep: hashlib.sha256(jar.read_bytes()).hexdigest() for dep, jar in zip(deps, jars)}}
    with tempfile.TemporaryDirectory(prefix="destiny-h28-") as temp:
        work = Path(temp)
        subprocess.run([str(java_home / "bin/javac"), "-cp", classpath, "-d", temp,
                        str(ROOT / "scripts/mesh/HunterMeshCompiler.java")], check=True)
        for key, old in (("arc", "arc_staff_h27"), ("bow", "shadow_bow_h27_drawn")):
            source = json.loads((SOURCE / f"{key}.mesh.json").read_text())
            base = json.loads((ASSETS / f"models/item/{old}.json").read_text())
            primitive = f"mesh/h28/{key}_triangle"
            subprocess.run([str(java_home / "bin/java"), "-cp", temp + os.pathsep + classpath,
                            "HunterMeshCompiler", str(SOURCE / f"{key}.mesh.json"),
                            str(work / f"{key}.json"), "destiny:" + primitive], check=True)
            compiled = json.loads((work / f"{key}.json").read_text())
            # Right triangle: north UV x<=y; south reverses U for the same spatial mask.
            prim = {"ambientocclusion": False, "display": base["display"],
                    "textures": {"0": "destiny:item/supers/mesh_triangle_h28", "particle": "destiny:item/supers/mesh_triangle_h28"},
                    "elements": [{"from": [-16, 0, 0], "to": [0, 16, 0], "shade": True,
                                  "light_emission": 0 if key == "arc" else 4,
                                  "faces": {"north": {"uv": [0, 0, 16, 16], "texture": "#0", "tintindex": 0},
                                            "south": {"uv": [16, 0, 0, 16], "texture": "#0", "tintindex": 0}}}]}
            output[ASSETS / f"models/{primitive}.json"] = encode(prim)
            names = ["arc_staff_h28"] if key == "arc" else ["shadow_bow_h28_drawn", "shadow_bow_h28"]
            for name in names:
                root = copy.deepcopy(compiled)
                if key == "bow":
                    # Original straight cord removed; inherited H22/H27 contract is real geometry.
                    tail = copy.deepcopy(base)
                    if name.endswith("_drawn"):
                        tail["elements"] = tail["elements"][-5:]
                    else:
                        old_rest = json.loads((ASSETS / "models/item/shadow_bow_h27.json").read_text())
                        tail["elements"] = old_rest["elements"][-1:]
                    root["models"].append({"type": "minecraft:model", "model": "destiny:item/" + name})
                else:
                    # Metadata model retains display/hand contract for tests/editors, not drawn.
                    tail = {"display": base["display"], "elements": []}
                output[ASSETS / f"models/item/{name}.json"] = encode(tail)
                output[ASSETS / f"items/{name}.json"] = encode({"model": root})
                manifest["models"][name] = {"mesh_triangles": len(source["triangles"]),
                                            "mesh_parts": len(compiled["models"]),
                                            "tail_cuboids": len(tail["elements"]),
                                            "raw_bounds": [[min(v[i] for v in source["vertices"]) for i in range(3)],
                                                           [max(v[i] for v in source["vertices"]) for i in range(3)]],
                                            "source_sha256": hashlib.sha256((SOURCE / f"{key}.mesh.json").read_bytes()).hexdigest()}
    manifest["runtime_sha256"] = {str(p.relative_to(ASSETS)): hashlib.sha256(data).hexdigest()
                                  for p, data in output.items()}
    output[SOURCE / "manifest.json"] = encode(manifest)
    return output


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--verify", action="store_true")
    args = parser.parse_args()
    for path, data in generate().items():
        if args.verify:
            assert path.read_bytes() == data, path
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
        print("verified" if args.verify else "wrote", path.relative_to(ROOT))
