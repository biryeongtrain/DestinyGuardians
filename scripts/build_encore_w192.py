    for weapon in catalog:
        item = inventory[str(weapon["bungieHash"])]
        sockets = item["sockets"]
        categories = [c for c in sockets["socketCategories"] if c["socketCategoryHash"] == TRAIT]
        matches = []
        for n in sorted({n for c in categories for n in c["socketIndexes"]}):
            socket = sockets["socketEntries"][n]
            ph = socket.get("randomizedPlugSetHash")
