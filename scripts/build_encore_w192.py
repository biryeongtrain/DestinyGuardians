def require(condition, message):
    if not condition:
        raise ValueError(message)


def encode(value):
    return (json.dumps(value, ensure_ascii=False, indent=2) + "\n").encode()


def plain(value):
    return " ".join(html.unescape(re.sub(r"<[^>]+>", " ", value)).split())


def generate(args):
    paths = {
        "inventory": args.inventory, "plugsets": args.plugsets, "manifest": args.manifest,
        "candidates": args.candidates, "ddc": args.ddc,
        "catalog": args.root / PREFIX / "w40-characteristics.json",
        "exotics83": args.root / PREFIX / "w83-exotics.json",
        "exotics84": args.root / PREFIX / "w84-exotics.json",
        "mapping": args.root / "art/weapons/w43/extraction.json",
        "formulas": args.root / "art/weapons/w46/weapon_formulas.json",
        "ballistics": args.root / PREFIX / "w43-ballistics.json",
    }
    inputs, data = {}, {}
    for name, path in paths.items():
        raw = path.read_bytes()
        digest = hashlib.sha256(raw).hexdigest()
        require(digest == PINS[name], "Input drift: " + name)
        # Workspace-relative provenance keeps the generated bytes independent of checkout location.
        location = str(path.relative_to(args.root)) if path.is_relative_to(args.root) else str(path)
        inputs[name] = {"path": location, "sha256": digest}
        data[name] = raw.decode() if name == "ddc" else json.loads(raw)
    inventory, pools = data["inventory"], data["plugsets"]
    manifest = data["manifest"]["Response"]
    require(manifest["version"] == VERSION, "Manifest version")
    perk = inventory[str(BASE)]
    require(perk["displayProperties"]["name"] == "Encore" and perk["itemTypeDisplayName"] == "Trait"
            and perk["plug"]["isDummyPlug"] is False and not perk.get("redacted")
            and not perk.get("blacklisted"), "Base Encore only")
