package kim.biryeong.destiny.campaign.model;

import kim.biryeong.destiny.DestinyGuardians;
import kim.biryeong.destiny.campaign.RisingServices;
import net.fabricmc.loader.api.FabricLoader;

import java.io.IOException;
import java.io.InputStream;
import java.nio.charset.StandardCharsets;
import java.nio.file.AtomicMoveNotSupportedException;
import java.nio.file.FileAlreadyExistsException;
import java.nio.file.Files;
import java.nio.file.LinkOption;
import java.nio.file.Path;
import java.nio.file.StandardCopyOption;
import java.nio.file.StandardOpenOption;
import java.security.MessageDigest;
import java.security.NoSuchAlgorithmException;
import java.util.HexFormat;
import java.util.List;

/**
 * Installs the W300 Guardian Rises BetterModel models (generated by scripts/campaign/rising_models.py)
 * into {@code config/bettermodel/models/NAME.bbmodel}.
 *
 * <p>Versioned overwrite: a SHA-256 marker of the last copy we installed is kept outside the BetterModel
 * scan folder ({@code config/destiny/guardian_rises/models/NAME.sha256}). A bundled update replaces the
 * installed file only while it is still byte-identical to our last install; a hand-edited, foreign or
 * symlinked file is left alone and logged. Only the eight {@code rg_*} names are ever touched.
 * Call {@link #prepare()} before BetterModel reloads (mod init, like the other *ModelAssets classes).</p>
 */
public final class RisingModelAssets {
    public static final List<String> MODELS = List.of(
            RisingServices.Models.GHOST, RisingServices.Models.DREG, RisingServices.Models.VANDAL,
            RisingServices.Models.CAPTAIN, RisingServices.Models.SHANK, RisingServices.Models.WALKER,
            RisingServices.Models.SKIFF, RisingServices.Models.SHIP);
    static final String RESOURCE_DIR = "/destiny/guardian_rises/models/";

    enum Outcome { INSTALLED, UPDATED, CURRENT, KEPT_USER_COPY, SKIPPED_LINK }

    private RisingModelAssets() { }

    public static void prepare() {
        Path config = FabricLoader.getInstance().getConfigDir();
        Path models = config.resolve("bettermodel/models");
        Path markers = config.resolve("destiny/guardian_rises/models");
        for (String name : MODELS) {
            try {
                byte[] bundled = bundled(name);
                Outcome outcome = install(models, markers, name, bundled);
                switch (outcome) {
                    case INSTALLED, UPDATED -> DestinyGuardians.LOGGER.info("Guardian Rises model {} {}", name, outcome);
                    case KEPT_USER_COPY -> DestinyGuardians.LOGGER.warn(
                            "Guardian Rises model {} differs from the bundled build and was not written by us; keeping it", name);
                    case SKIPPED_LINK -> DestinyGuardians.LOGGER.warn("Guardian Rises model {} is a symlink; not touching it", name);
                    case CURRENT -> { }
                }
            } catch (Exception e) {
                // Cosmetic failure must not stop startup; the director falls back to the vanilla entity body.
                DestinyGuardians.LOGGER.warn("Cannot install Guardian Rises model {}: {}", name, e.toString());
            }
        }
    }

    static byte[] bundled(String name) throws IOException {
        try (InputStream in = RisingModelAssets.class.getResourceAsStream(RESOURCE_DIR + name + ".bbmodel")) {
            if (in == null) throw new IOException("bundled model missing: " + name);
            return in.readAllBytes();
        }
    }

    static Outcome install(Path modelsDir, Path markerDir, String name, byte[] bundled) throws IOException {
        if (!MODELS.contains(name)) throw new IllegalArgumentException("not a Guardian Rises model: " + name);
        return installOwned(modelsDir, markerDir, name, bundled);
    }

    /** Shared versioned writer; each asset catalog validates its own exact model allowlist. */
    static Outcome installOwned(Path modelsDir, Path markerDir, String name, byte[] bundled) throws IOException {
        if (!name.matches("[a-z][a-z0-9_]*")) throw new IllegalArgumentException("Invalid model name");
        Files.createDirectories(modelsDir);
        Files.createDirectories(markerDir);
        Path target = modelsDir.resolve(name + ".bbmodel");
        Path marker = markerDir.resolve(name + ".sha256");
        String want = sha256(bundled);
        if (Files.isSymbolicLink(target)) return Outcome.SKIPPED_LINK;
        if (!Files.exists(target, LinkOption.NOFOLLOW_LINKS)) {
            try {
                Files.write(target, bundled, StandardOpenOption.CREATE_NEW, StandardOpenOption.WRITE);
            } catch (FileAlreadyExistsException race) {
                return install(modelsDir, markerDir, name, bundled);
            }
            writeMarker(marker, want);
            return Outcome.INSTALLED;
        }
        String have = sha256(Files.readAllBytes(target));
        if (have.equals(want)) {
            writeMarker(marker, want);
            return Outcome.CURRENT;
        }
        String ours = Files.isRegularFile(marker, LinkOption.NOFOLLOW_LINKS)
                ? Files.readString(marker, StandardCharsets.UTF_8).trim() : "";
        if (!have.equals(ours)) return Outcome.KEPT_USER_COPY;
        Path temp = modelsDir.resolve("." + name + ".bbmodel.w300tmp");
        Files.write(temp, bundled, StandardOpenOption.CREATE, StandardOpenOption.TRUNCATE_EXISTING, StandardOpenOption.WRITE);
        try {
            Files.move(temp, target, StandardCopyOption.REPLACE_EXISTING, StandardCopyOption.ATOMIC_MOVE);
        } catch (AtomicMoveNotSupportedException e) {
            Files.move(temp, target, StandardCopyOption.REPLACE_EXISTING);
        }
        writeMarker(marker, want);
        return Outcome.UPDATED;
    }

    private static void writeMarker(Path marker, String hash) throws IOException {
        if (Files.isSymbolicLink(marker)) return;
        Files.writeString(marker, hash + "\n", StandardCharsets.UTF_8);
    }

    static String sha256(byte[] data) {
        try {
            return HexFormat.of().formatHex(MessageDigest.getInstance("SHA-256").digest(data));
        } catch (NoSuchAlgorithmException e) {
            throw new IllegalStateException(e);
        }
    }
}
